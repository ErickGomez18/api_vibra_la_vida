// ============================================================================
// HEALTH ROUTES
// ============================================================================


// ============================================================================
// EXPRESS
// ============================================================================

const express =
  require("express");


// ============================================================================
// CONTROLADORES
// ============================================================================

const {

  syncHealthData,

  getLatestHealthData,

  getHealthHistory,

  deleteHealthRecord,

} =
  require(
    "../controllers/health.controller"
  );


// ============================================================================
// AUTENTICACIÓN
// ============================================================================

const {
  verifyFirebaseToken,
} =
  require(
    "../middlewares/auth.middleware"
  );


// ============================================================================
// ROUTER
// ============================================================================

const router =
  express.Router();


// ============================================================================
// SINCRONIZAR DATOS
// ============================================================================
//
// POST /api/health-connect/sync
//
// Guarda o actualiza el resumen diario.
//
// ============================================================================

router.post(

  "/sync",

  verifyFirebaseToken,

  syncHealthData
);


// ============================================================================
// ÚLTIMO REGISTRO
// ============================================================================
//
// GET /api/health-connect/latest
//
// ============================================================================

router.get(

  "/latest",

  verifyFirebaseToken,

  getLatestHealthData
);


// ============================================================================
// HISTORIAL
// ============================================================================
//
// GET /api/health-connect/history
//
// Opcional:
//
// GET /api/health-connect/history?limit=30
//
// ============================================================================

router.get(

  "/history",

  verifyFirebaseToken,

  getHealthHistory
);


// ============================================================================
// ELIMINAR REGISTRO
// ============================================================================
//
// DELETE /api/health-connect/:id
//
// ============================================================================

router.delete(

  "/:id",

  verifyFirebaseToken,

  deleteHealthRecord
);


// ============================================================================
// EXPORTAR
// ============================================================================

module.exports =
  router;
