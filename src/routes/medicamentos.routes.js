// ============================================================================
// MEDICAMENTOS ROUTES
// ============================================================================

const express =
  require("express");


const router =
  express.Router();


// ============================================================================
// CONTROLLER
// ============================================================================

const {

  getMedicamentos,

  createMedicamento,

  updateMedicamento,

  deleteMedicamento,

} =
  require("../controllers/medicamentos.controller");


// ============================================================================
// MIDDLEWARE DE AUTENTICACIÓN
// ============================================================================

const {

  verifyFirebaseToken,

} =
  require("../middlewares/auth.middleware");


// ============================================================================
// OBTENER MEDICAMENTOS
// ============================================================================
//
// GET /api/medicamentos
//
// ============================================================================

router.get(

  "/",

  verifyFirebaseToken,

  getMedicamentos
);


// ============================================================================
// CREAR MEDICAMENTO
// ============================================================================
//
// POST /api/medicamentos
//
// ============================================================================

router.post(

  "/",

  verifyFirebaseToken,

  createMedicamento
);


// ============================================================================
// ACTUALIZAR MEDICAMENTO
// ============================================================================
//
// PUT /api/medicamentos/:id
//
// ============================================================================

router.put(

  "/:id",

  verifyFirebaseToken,

  updateMedicamento
);


// ============================================================================
// ELIMINAR MEDICAMENTO
// ============================================================================
//
// DELETE /api/medicamentos/:id
//
// ============================================================================

router.delete(

  "/:id",

  verifyFirebaseToken,

  deleteMedicamento
);


// ============================================================================
// EXPORTAR ROUTER
// ============================================================================

module.exports =
  router;